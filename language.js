const contentObserver = new MutationObserver((mutations) => {
  if (document.documentElement.lang !== 'ur') return;
  for (const mutation of mutations) {
    for (const addedNode of mutation.addedNodes) {
      if (addedNode.nodeType === Node.ELEMENT_NODE) {
        translateTree(addedNode, 'ur');
      } else if (addedNode.nodeType === Node.TEXT_NODE && addedNode.parentElement && !originalText.has(addedNode)) {
        originalText.set(addedNode, addedNode.nodeValue);
        const phrase = addedNode.nodeValue.trim();
        if (urduTranslations[phrase]) {
          addedNode.nodeValue = addedNode.nodeValue.replace(phrase, urduTranslations[phrase]);
        }
      }
    }
  }
});
contentObserver.observe(document.body, { childList: true, subtree: true });
